/** The five God task themes; the label is also the task's context. */
enum class GodTheme(val label: String) {
    GRATITUDE("Gratitude"), LEADERSHIP("Leadership"), NETWORKING("Networking"), HEALTH("Health"), FAMILY("Family");

    /** Thirty short activities (under 15 minutes each). Family ones name a family member through `{name}`. */
    val tasks: List<String> get() = GodTaskLibrary.tasks.getValue(this)

    companion object {
        fun of(name: String): GodTheme? = entries.firstOrNull { it.name == name }
    }
}

